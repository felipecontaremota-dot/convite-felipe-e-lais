// Embed the unmodified, locally vendored URW fonts. No runtime network/font lookup.
import { readFileSync, writeFileSync } from "node:fs";
const fonts = Object.fromEntries(
  ["Roman", "Bold"].map((style) => [
    style.toLowerCase(),
    readFileSync(
      new URL(`../assets/pdf/fonts/P052-${style}.ttf`, import.meta.url),
    ).toString("base64"),
  ]),
);
writeFileSync(
  new URL("../src/features/guests/guestPdfFonts.generated.ts", import.meta.url),
  `// Generated by scripts/generate-guest-pdf-fonts.mjs. See assets/pdf/fonts/LICENSE.\nexport const guestPdfFonts = ${JSON.stringify(fonts)} as const;\n`,
);
